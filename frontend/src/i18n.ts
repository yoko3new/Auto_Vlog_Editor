export function localizeMessage(message: string, language: Language): string {
  if (language === 'en') return message;
  if (message === 'A bundled preset is missing or changed. Restore the application assets.') return '内置资源缺失或已变化，请恢复应用资源文件。';
  if (message === 'A caption contains unsupported font glyphs. Remove emoji or use supported text.') return '字幕含字体不支持的字符，请移除表情符号或改用可显示的文字。';
  if (message === 'Mixing background music') return zh.mixingMusic;
  if (errors[message]) return errors[message];
  const patterns: [RegExp, string][] = [
    [/^Inspecting (\d+)\/(\d+)$/, '正在解析视频 $1/$2'],
    [/^Preparing video (\d+)\/(\d+)$/, '正在准备视频 $1/$2'],
    [/^Checking black frames (\d+)\/(\d+)$/, '正在检查黑场 $1/$2'],
    [/^Time ranges must be within the current film \(0–([\d.]+)s\) and span at least one frame\.$/, '时间区间须在当前成片 0–$1 秒内，且至少包含一帧。'],
    [/^AI analysis (\d+)\/(\d+)$/, '正在分析画面 $1/$2'],
    [/^Analysis cached: (\d+)\/(\d+)$/, '使用画面分析缓存 $1/$2'],
    [/^Speech recognition (\d+)\/(\d+)$/, '正在识别语音 $1/$2'],
    [/^Speech cached: (\d+)\/(\d+)$/, '使用语音识别缓存 $1/$2'],
    [/^Rendering (\d+)\/(\d+): .+$/, '正在渲染 $1/$2'],
    [/^Rendering cached (\d+)\/(\d+)$/, '使用已渲染片段 $1/$2'],
    [/^Complete: .+$/, '影片已完成。'],
    [/^Request failed \((\d+)\)\.$/, '请求失败（$1），请检查设置后重试。'],
  ];
  for (const [pattern, replacement] of patterns) if (pattern.test(message)) return message.replace(pattern, replacement);
  return message;
}
